#!/usr/bin/env python3
"""Embed the iOS port's JavaScript assets into a generated Objective-C header."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / "Resources"
OUTPUT = ROOT / "Generated" / "QTEmbeddedScripts.h"

ASSETS = [
    ("QTShimJS", RESOURCES / "quiz-tutor-shim.js"),
    ("QTContentJS", RESOURCES / "content.js"),
]

def byte_array(name: str, data: bytes) -> str:
    rows = []
    for start in range(0, len(data), 16):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[start:start + 16]))
    return f"static const unsigned char {name}[] = {{\n" + ",\n".join(rows) + "\n};\n"

parts = [
    "// Generated by scripts/embed_resources.py. Do not edit manually.\n",
    "#ifndef QT_EMBEDDED_SCRIPTS_H\n#define QT_EMBEDDED_SCRIPTS_H\n\n",
]
for name, path in ASSETS:
    if not path.is_file():
        raise SystemExit(f"Missing JavaScript input: {path}")
    data = path.read_bytes()
    if not data:
        raise SystemExit(f"JavaScript input is empty: {path}")
    parts.append(byte_array(name, data))
    print(f"Embedded {path.name}: {len(data)} bytes")
parts.append("\n#endif // QT_EMBEDDED_SCRIPTS_H\n")
OUTPUT.parent.mkdir(parents=True, exist_ok=True)
OUTPUT.write_text("\n".join(parts), encoding="ascii")
print(f"Wrote {OUTPUT}")
